#!/usr/bin/env bash

PROTECTED_URL_DEFAULT=""

export PROTECTED_URL=${PROTECTED_URL:-"${PROTECTED_URL_DEFAULT}"}

HTPASSWD_USERNAME_DEFAULT="default"
HTPASSWD_PASSWORD_DEFAULT="password"

export HTPASSWD_USERNAME=${HTPASSWD_USERNAME:-"${HTPASSWD_USERNAME_DEFAULT}"}
export HTPASSWD_PASSWORD=${HTPASSWD_PASSWORD:-"${HTPASSWD_PASSWORD_DEFAULT}"}

HTPASSWD_FILE_DEFAULT="/app/etc/apache2/.htpasswd"

export HTPASSWD_FILE="${HTPASSWD_FILE:-"${HTPASSWD_FILE_DEFAULT}"}"

true
